/**
 * Calculates a dynamic upcoming train departure time in Mumbai local time (Asia/Kolkata timezone).
 * Ensures the scheduled departure time is always strictly in the future relative to the current local Mumbai time.
 */
export const getMumbaiNextTrainTime = (offsetMinutes: number = 3): string => {
  const targetDate = new Date(Date.now() + Math.max(1, offsetMinutes) * 60 * 1000);
  return new Intl.DateTimeFormat('en-US', {
    timeZone: 'Asia/Kolkata',
    hour: '2-digit',
    minute: '2-digit',
    hour12: true
  }).format(targetDate);
};

export const getStationTrainOffset = (stationId: string, platformNum: number = 1): number => {
  let hash = 0;
  for (let i = 0; i < stationId.length; i++) {
    hash = (hash * 31 + stationId.charCodeAt(i)) & 0xffffffff;
  }
  const baseOffset = (Math.abs(hash) % 5) + 2; // 2 to 6 minutes
  return baseOffset + (platformNum > 1 ? (platformNum - 1) * 2 : 0);
};

// Bind dynamic property getters on MOCK_STATIONS so nextTrain and platform nextTrainTime
// always evaluate dynamically relative to current Mumbai local time (Asia/Kolkata)
MOCK_STATIONS.forEach((station) => {
  const stationOffset = getStationTrainOffset(station.id, station.platform || 1);
  Object.defineProperty(station, 'nextTrain', {
    get() {
      return getMumbaiNextTrainTime(stationOffset);
    },
    enumerable: true,
    configurable: true
  });

  if (station.platforms) {
    station.platforms.forEach((p) => {
      const platOffset = getStationTrainOffset(station.id, p.platformNumber);
      Object.defineProperty(p, 'nextTrainTime', {
        get() {
          return getMumbaiNextTrainTime(platOffset);
        },
        enumerable: true,
        configurable: true
      });
    });
  }
});

